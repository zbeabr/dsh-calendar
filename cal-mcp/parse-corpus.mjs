const pad = (n) => String(n).padStart(2, '0');
const stamp = (date) => `${pad(date.getMonth() + 1)}-${pad(date.getDate())} ${pad(date.getHours())}:${pad(date.getMinutes())}`;

/** 把一条解析结果压成一行可读文本；报错也记下来（报错文案同样是契约）。 */
function render(text) {
  try {
    const r = parseEvent(text, NOW, { calendarNames: NAMES });
    const rep = r.repeat
      ? [r.repeat.freq, r.repeat.interval > 1 ? `INTERVAL=${r.repeat.interval}` : null,
        r.repeat.byday?.join(','), r.repeat.bymonthday].filter(Boolean).join(' ')
      : '-';
    return [
      r.title, stamp(r.start), stamp(r.end), r.allDay ? 'allDay' : '-',
      r.location ?? '-', r.calendar ?? '-', rep,
      r.alarmMinutes ?? '-', r.rolled ? 'rolled' : '-',
      r.durationAssumed ? 'assumed' : '-',
    ].join(' | ');
  } catch (error) {
    return `ERROR | ${error.message}`;
  }
}

const lines = CORPUS.map(([category, text], index) =>
  `${String(index + 1).padStart(3, '0')}\t${category}\t${text}\t=>\t${render(text)}`);

const mode = process.argv[2] ?? '';

if (mode === '--show') {
  console.log(lines.join('\n'));
  console.log(`\n共 ${lines.length} 条`);
} else if (mode === '--record') {
  writeFileSync(SNAPSHOT, `${lines.join('\n')}\n`, 'utf8');
  console.log(`✓ 已固化 ${lines.length} 条到 ${SNAPSHOT}`);
} else if (mode === '--audit') {
  // 只标「看着不对」的，真正的判断仍由人做；这些启发式不参与快照比对。
  // 用绝对时间戳算时长，别拿 "11-05 12:00" 这种字符串硬拼年份（跨年 / 全天会误报）。
  const suspicious = /明天|今天|后天|大后天|下个?周|下下|周末|点钟|点半|小时|分钟|用时|提前|每周|每天|每月|#|＃|，|,|。/u;
  let count = 0;
  lines.forEach((line, index) => {
    const [category, text] = CORPUS[index];
    const result = line.split('\t=>\t')[1];
    let parsed;
    try { parsed = parseEvent(text, NOW, { calendarNames: NAMES }); } catch { parsed = null; }
    const errored = parsed === null;
    const reasons = [];
    if (errored && category !== '预期报错') reasons.push('意外报错');
    if (!errored && category === '预期报错') reasons.push('本该报错却通过');
    if (!errored) {
      const title = parsed.title;
      if (title.length < 2) reasons.push('标题过短');
      if (suspicious.test(title)) reasons.push('标题疑似残留时间词');
      // 「去露营」「到公司」是正常动词短语，只有介词后紧跟空白/标点才算残渣
      if (/^[在到去于](?=[\s，,、]|$)|^[的]/u.test(title)) reasons.push('标题以介词/助词开头');
      // 「吃点好的」以「的」收尾是对的，只报「个的」这种剥离残渣
      if (/(个的|用时|大概|约|在$)/u.test(title)) reasons.push('标题残留虚词');
      const hours = (parsed.end.getTime() - parsed.start.getTime()) / 3600000;
      // 「现在到明天中午」本来就跨十几个小时，不算异常
      if (!/^(从)?现在到/u.test(text) && (hours <= 0 || (hours > 12 && !parsed.allDay))) {
        reasons.push(`时长异常 ${hours}h`);
      }
      if (parsed.allDay && hours !== 24) reasons.push(`全天才 ${hours}h`);
    }
    if (reasons.length > 0) {
      count += 1;
      console.log(`${line.split('\t')[0]} [${category}] ${text}\n    ${reasons.join('；')}\n    ${result}`);
    }
  });
  console.log(`\n可疑 ${count} / ${lines.length} 条（需人工逐条判断，不等于就是 bug）`);
} else {
  if (!existsSync(SNAPSHOT)) {
    console.error(`✗ 找不到快照 ${SNAPSHOT}，先跑 node parse-corpus.mjs --record`);
    process.exit(1);
  }
  const expected = readFileSync(SNAPSHOT, 'utf8').trimEnd().split('\n');
  let failed = 0;
  for (let i = 0; i < Math.max(expected.length, lines.length); i += 1) {
    if (expected[i] === lines[i]) continue;
    failed += 1;
    console.log(`✗ 第 ${i + 1} 条 ${CORPUS[i]?.[1] ?? '(快照多出的行)'}`);
    console.log(`    快照：${expected[i] ?? '(无)'}`);
    console.log(`    当前：${lines[i] ?? '(无)'}`);
  }
  if (failed > 0) {
    console.log(`\n✗ ${failed} 条与核验蓝本不一致。若确认是解析器改对了，人工看 --show 后再 --record。`);
    process.exit(1);
  }
  console.log(`✓ ${lines.length} 条口语解析与核验蓝本完全一致`);
  process.exit(0);
}
